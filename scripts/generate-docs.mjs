const groups = [
    { name: 'players', title: 'Players', description: 'Player profiles, match history, aggregated statistics, rankings, and refresh requests.' },
    { name: 'matches', title: 'Matches', description: 'Match details, sampled match lists, live games, and replay parse requests.' },
    { name: 'heroes', title: 'Heroes', description: 'Hero metadata, performance statistics, matchups, rankings, and benchmarks.' },
    { name: 'teams', title: 'Teams', description: 'Team profiles and their match, player, and hero statistics.' },
    { name: 'leagues', title: 'Leagues', description: 'League metadata and associated matches, match IDs, and teams.' },
    { name: 'scenarios', title: 'Scenarios', description: 'Aggregated outcomes for item timings, lane roles, and team scenarios.' },
    { name: 'service', title: 'Service and resources', description: 'Service health, metadata, database queries, schema, and game constants.' },
];

function groupFor(path) {
    if (path.startsWith('/players') || ['/proPlayers', '/topPlayers', '/search'].includes(path)) return 'players';
    if (path.startsWith('/heroes') || ['/heroStats', '/rankings', '/benchmarks'].includes(path)) return 'heroes';
    if (path.startsWith('/teams')) return 'teams';
    if (path.startsWith('/leagues')) return 'leagues';
    if (path.startsWith('/scenarios')) return 'scenarios';
    if (path.startsWith('/matches') || path.startsWith('/request/') || ['/proMatches', '/publicMatches', '/parsedMatches', '/findMatches', '/records/{field}', '/live'].includes(path)) return 'matches';
    return 'service';
}

function cell(value) {
    return String(value).replaceAll('|', '\\|').replaceAll(/\r?\n/g, ' ');
}

function code(value) {
    return `\`${String(value)}\``;
}

function header(title, contract) {
    return [
        `# ${title}`,
        '',
        '<!-- Generated by scripts/generate.mjs. Do not edit this file directly. -->',
        '',
        `Generated from the saved OpenDota ${contract.version} contract (OpenAPI ${contract.openapi}), retrieved ${contract.retrievedDate}, with the package's [contract corrections](${title === 'Operation index' || title === 'Response schemas' ? '' : '../'}contract-corrections.md).`,
        '',
    ];
}

function resolve(spec, value) {
    if (!value?.$ref) return value;
    return value.$ref.split('/').slice(1).reduce((current, key) => current?.[key], spec);
}

function schemaType(schema, schemaLink) {
    if (!schema || typeof schema !== 'object') return code('unknown');
    let value;
    if (schema.$ref) {
        const name = schema.$ref.split('/').at(-1);
        value = `[${code(name)}](${schemaLink}#${name.toLowerCase()})`;
    } else if (schema.format === 'opendota-decimal-id') {
        value = code('DecimalId');
    } else if (schema.format === 'opendota-numeric-boolean' || schema.format === 'opendota-turbo-boolean') {
        value = code('0 | 1 | boolean');
    } else if (schema.enum) {
        value = code(schema.enum.map((item) => JSON.stringify(item)).join(' | '));
    } else if (schema.oneOf || schema.anyOf || schema.allOf) {
        const parts = schema.oneOf ?? schema.anyOf ?? schema.allOf;
        const separator = schema.allOf ? ' & ' : ' or ';
        value = parts.map((part) => schemaType(part, schemaLink)).join(separator);
    } else if (schema.type === 'array') {
        const item = schemaType(schema.items, schemaLink);
        const needsGrouping = schema.items?.oneOf || schema.items?.anyOf || schema.items?.allOf || schema.items?.nullable;
        value = `Array of ${needsGrouping ? `(${item})` : item}`;
    } else if (schema.type === 'object' || schema.properties || schema.additionalProperties) {
        const hasProperties = Object.keys(schema.properties ?? {}).length > 0;
        if (!hasProperties && schema.additionalProperties) {
            const item = schema.additionalProperties === true ? code('unknown') : schemaType(schema.additionalProperties, schemaLink);
            value = `String-keyed object of ${item}`;
        } else {
            value = code('object');
        }
    } else if (schema.type === 'integer' || schema.type === 'number') {
        value = code('number');
    } else if (schema.type) {
        value = code(schema.type);
    } else {
        value = code('unknown');
    }
    return schema.nullable ? `${value} or ${code('null')}` : value;
}

function schemaDescription(schema) {
    const details = [];
    if (schema.description) details.push(schema.description);
    if (schema.type === 'integer' && !schema.format?.startsWith('opendota-')) details.push('Integer.');
    if (schema.format === 'opendota-decimal-id') details.push('Decimal string identifier.');
    if (schema.format && !schema.format.startsWith('opendota-')) details.push(`Format: ${code(schema.format)}.`);
    for (const [property, label] of [['minimum', 'Minimum'], ['maximum', 'Maximum'], ['minItems', 'Minimum items'], ['maxItems', 'Maximum items'], ['minLength', 'Minimum length'], ['maxLength', 'Maximum length'], ['pattern', 'Pattern']]) {
        if (schema[property] !== undefined) details.push(`${label}: ${code(schema[property])}.`);
    }
    return details.join(' ') || 'Not described in the saved contract.';
}

function fields(schema, prefix = '') {
    if (!schema || schema.$ref) return [];
    if (schema.type === 'array') return fields(schema.items, `${prefix}[]`);
    const rows = [];
    const required = new Set(schema.required ?? []);
    for (const [name, property] of Object.entries(schema.properties ?? {}).sort(([left], [right]) => left.localeCompare(right))) {
        const path = prefix ? `${prefix}.${name}` : name;
        rows.push({ path, schema: property, required: required.has(name) ? 'Yes' : 'No' });
        rows.push(...fields(property, path));
    }
    if (schema.additionalProperties) {
        const additional = schema.additionalProperties === true ? {} : schema.additionalProperties;
        const path = `${prefix}[key]`;
        rows.push({ path, schema: additional, required: 'Dynamic', description: 'Additional string keys; the saved contract does not enumerate them.' });
        rows.push(...fields(additional, path));
    }
    return rows;
}

function fieldTable(schema, schemaLink) {
    const rows = fields(schema);
    if (!rows.length) return [];
    return [
        '| Field path | Type | Required | Description |',
        '| --- | --- | --- | --- |',
        ...rows.map((row) => `| ${code(row.path)} | ${cell(schemaType(row.schema, schemaLink))} | ${row.required} | ${cell(row.description ?? schemaDescription(row.schema))} |`),
        '',
    ];
}

function parameterTable(parameters, location) {
    const selected = parameters.filter((parameter) => parameter.in === location);
    if (!selected.length) return [`${location === 'path' ? 'Path' : 'Query'} parameters: none.`, ''];
    return [
        `#### ${location === 'path' ? 'Path' : 'Query'} parameters`,
        '',
        '| Name | Type | Required | Default | Description |',
        '| --- | --- | --- | --- | --- |',
        ...selected.map((parameter) => {
            const schema = parameter.schema ?? {};
            const parameterDescription = parameter.name === 'sql' && parameter.description?.includes('percent-encoded')
                ? 'Raw PostgreSQL query text. The SDK handles URL encoding.'
                : parameter.description;
            const description = [parameterDescription, schemaDescription({ ...schema, description: undefined })]
                .filter((value) => value && value !== 'Not described in the saved contract.').join(' ');
            const defaultValue = schema.default !== undefined
                ? code(JSON.stringify(schema.default))
                : parameter.name === 'significant' && parameter.description?.includes('Defaults to 1')
                    ? `${code('1')} (provider description)`
                    : 'Not specified';
            return `| ${code(parameter.name)} | ${cell(schemaType(schema, '../schemas.md'))} | ${parameter.required ? 'Yes' : 'No'} | ${cell(defaultValue)} | ${cell(description || 'Not described in the saved contract.')} |`;
        }),
        '',
    ];
}

function exampleValue(parameter) {
    const schema = parameter.schema ?? {};
    if (schema.default !== undefined) return JSON.stringify(schema.default);
    if (schema.enum?.length) return JSON.stringify(schema.enum[0]);
    if (schema.format === 'opendota-decimal-id') {
        return JSON.stringify({ account_id: '123456789', match_id: '90071992547409931', league_id: '12345', team_id: '12345' }[parameter.name] ?? '12345');
    }
    if (schema.type === 'integer' || schema.type === 'number') return '1';
    if (schema.type === 'boolean') return 'true';
    const value = { field: 'kills', resource: 'heroes', jobId: 'example-job-id', sql: 'SELECT 1', q: 'example-player', hero_id: '1' }[parameter.name] ?? 'example';
    return JSON.stringify(value);
}

function callExample(operation, parameters) {
    const required = parameters.filter((parameter) => parameter.required || parameter.in === 'path');
    const options = ['path', 'query'].flatMap((location) => {
        const entries = required.filter((parameter) => parameter.in === location);
        return entries.length ? [`  ${location}: { ${entries.map((parameter) => `${parameter.name}: ${exampleValue(parameter)}`).join(', ')} },`] : [];
    });
    const method = operation.method.toLowerCase();
    const start = `const { data, meta } = await client.${method}(${JSON.stringify(operation.path)}`;
    return [
        '```ts',
        options.length ? `${start}, {` : `${start}, {});`,
        ...options,
        ...(options.length ? ['});'] : []),
        '```',
        '',
    ];
}

function endpointSection(spec, operation) {
    const method = operation.method.toLowerCase();
    const definition = spec.paths[operation.path][method];
    const parameters = [...(spec.paths[operation.path].parameters ?? []), ...(definition.parameters ?? [])].map((parameter) => resolve(spec, parameter));
    const success = definition.responses?.['200'];
    const media = Object.entries(success?.content ?? {});
    const schema = media[0]?.[1]?.schema;
    return [
        `<a id="${operation.operationId}"></a>`,
        '',
        `## ${operation.method} ${code(operation.path)}`,
        '',
        operation.summary,
        '',
        `Operation ID: ${code(operation.operationId)}.`,
        '',
        '### SDK call',
        '',
        ...callExample(operation, parameters),
        '### Parameters',
        '',
        ...parameterTable(parameters, 'path'),
        ...parameterTable(parameters, 'query'),
        ...(method === 'post' ? ['Request body: none; the SDK does not accept a body for this operation.', ''] : []),
        '### Success response',
        '',
        `HTTP ${code('200')}${media.length ? `; content type ${code(media[0][0])}` : ''}. ${success?.description ?? ''}`.trim(),
        '',
        `The SDK resolves to ${code('OpenDotaResult<Data>')}. ${code('data')} has the shape: ${schemaType(schema, '../schemas.md')}. ${code('meta')} is documented in [Response metadata](../client.md#results-and-metadata).`,
        '',
        '```ts',
        "import type { ResponseData } from '@reino-doce/opendota-client';",
        '',
        `type Data = ResponseData<${JSON.stringify(operation.path)}, ${JSON.stringify(method)}>;`,
        '```',
        '',
        ...fieldTable(schema, '../schemas.md'),
    ];
}

function endpointPage(spec, contract, operations, group) {
    const selected = operations.filter((operation) => groupFor(operation.path) === group.name);
    return [
        ...header(`${group.title} endpoints`, contract),
        '[Documentation home](../README.md) · [All operations](../operations.md) · [Client API](../client.md) · [Requests](../requests.md) · [Errors](../errors.md) · [Schemas](../schemas.md)',
        '',
        group.description,
        '',
        'Examples assume an initialized `client`; see [client construction and lifecycle](../client.md). Example inputs illustrate SDK types and do not identify verified provider records.',
        '',
        'Response tables describe the saved contract. Fields marked "No" may be absent. Nested required flags apply within their containing object; `[]` denotes an array element and `[key]` an unspecified string key. `unknown` values need application-level narrowing. See [schema conventions](../schemas.md#reading-the-schemas).',
        '',
        '| Method | Route | Operation |',
        '| --- | --- | --- |',
        ...selected.map((operation) => `| ${operation.method} | ${code(operation.path)} | [${code(operation.operationId)}](#${operation.operationId}) |`),
        '',
        ...selected.flatMap((operation) => endpointSection(spec, operation)),
    ].join('\n');
}

function operationIndex(contract, operations) {
    return [
        ...header('Operation index', contract),
        '[Documentation home](README.md) · [Client API](client.md) · [Requests](requests.md) · [Errors](errors.md) · [Schemas](schemas.md)',
        '',
        `${operations.length} operations: ${operations.filter((operation) => operation.method === 'GET').length} GET and ${operations.filter((operation) => operation.method === 'POST').length} POST. Each operation links to its call example, path and query parameters, and success response shape.`,
        '',
        ...groups.flatMap((group) => {
            const selected = operations.filter((operation) => groupFor(operation.path) === group.name);
            return [
                `## [${group.title}](endpoints/${group.name}.md)`,
                '',
                group.description,
                '',
                '| Method | Route | Operation | Description |',
                '| --- | --- | --- | --- |',
                ...selected.map((operation) => `| ${operation.method} | ${code(operation.path)} | [${code(operation.operationId)}](endpoints/${group.name}.md#${operation.operationId}) | ${cell(operation.summary)} |`),
                '',
            ];
        }),
    ].join('\n');
}

function schemasPage(spec, contract) {
    const schemas = Object.entries(spec.components.schemas).sort(([left], [right]) => left.localeCompare(right));
    return [
        ...header('Response schemas', contract),
        '[Documentation home](README.md) · [Operation index](operations.md) · [Client API](client.md) · [Requests](requests.md) · [Errors](errors.md)',
        '',
        '## Reading the schemas',
        '',
        '- These models describe the saved contract after the package corrections. They are documentation labels, not separately exported package types. Use the public `ResponseData<Route, Method>` type for an endpoint, then index into it for nested types.',
        '- Required means listed in the containing object\'s `required` array. A field marked "No" is optional; optionality is separate from an explicit `null` value. A nested required field can only be read after checking its optional parents.',
        '- `number` covers the schema\'s integer and number types; integer constraints and declared formats appear in descriptions. `DecimalId` is the exported `string` alias used for corrected decimal identifiers.',
        '- `unknown` means the contract leaves the value unspecified. A string-keyed object of `unknown` retains unspecified provider fields. Narrow such values before accessing them.',
        '- A field path with `[]` refers to an array element; `[key]` refers to an arbitrary string key. Linked model names open their field tables. Inline response models are documented on their endpoint pages.',
        '- These are TypeScript contract descriptions. The transport parses JSON and preserves provider fields; it does not validate responses against these schemas. Unsafe non-identifier integers can be retained as decimal strings by the lossless JSON parser even where the static schema says `number`; see [response data](requests.md#response-data).',
        '',
        '## Model index',
        '',
        ...schemas.map(([name]) => `- [${code(name)}](#${name.toLowerCase()})`),
        '',
        ...schemas.flatMap(([name, schema]) => [
            `<a id="${name.toLowerCase()}"></a>`,
            '',
            `## ${name}`,
            '',
            ...(schema.description ? [schema.description, ''] : []),
            `Shape: ${schemaType(schema, '')}.`,
            '',
            ...fieldTable(schema, ''),
        ]),
    ].join('\n');
}

export function generateDocumentation(spec, contract, operations) {
    return new Map([
        ['docs/operations.md', operationIndex(contract, operations)],
        ['docs/schemas.md', schemasPage(spec, contract)],
        ...groups.map((group) => [`docs/endpoints/${group.name}.md`, endpointPage(spec, contract, operations, group)]),
    ]);
}
